// Editorial interpretations for a playful game, not official character psychology.
// filmId groups adaptations and sequels so each film family has at most three entries.
const character = (
  id,
  name,
  symbol,
  tagline,
  description,
  values,
  image = null,
) => ({
  id,
  name,
  symbol,
  tagline,
  description,
  image,
  profile: {
    entusiasmo: values[0],
    ingegno: values[1],
    tradizione: values[2],
    ironia: values[3],
    spettacolo: values[4],
  },
});
const film = (filmId, movie, characters) =>
  characters.map((entry) => ({ ...entry, filmId, movie }));

